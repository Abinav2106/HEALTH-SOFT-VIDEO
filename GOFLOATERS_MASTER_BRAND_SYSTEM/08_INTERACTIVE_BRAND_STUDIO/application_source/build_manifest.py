"""Scan the package and write assets/manifest.js for the Brand Studio (asset library,
animation list, gallery). Run from anywhere: python3 build_manifest.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
STUDIO = os.path.dirname(HERE); ROOT = os.path.dirname(STUDIO)
SKIP = ('tools/build', '08_INTERACTIVE_BRAND_STUDIO', '07_BRAND_GUIDELINES/editable_source/stills', '07_BRAND_GUIDELINES/page_previews', '09_BRAND_APPLICATIONS/source', '.git')
EXT = {'.svg': 'Vector', '.png': 'Image', '.jpg': 'Image', '.mp4': 'Video', '.webm': 'Video', '.pdf': 'Document', '.json': 'Data', '.css': 'Code', '.js': 'Code', '.zip': 'Archive', '.woff2': 'Font'}
files = []
for dp, dn, fn in os.walk(ROOT):
    rel = os.path.relpath(dp, ROOT)
    if any(rel.startswith(s) for s in SKIP) or rel.startswith('tools'):
        continue
    for f in sorted(fn):
        e = os.path.splitext(f)[1].lower()
        if e not in EXT: continue
        p = os.path.join(rel, f) if rel != '.' else f
        files.append({'path': p.replace(os.sep, '/'), 'section': p.split('/')[0], 'kind': EXT[e], 'bytes': os.path.getsize(os.path.join(dp, f))})
files.sort(key=lambda x: x['path'])
videos = [f for f in files if f['kind'] == 'Video' and f['path'].endswith('.mp4')]
gallery = [f for f in files if f['path'].startswith('09_BRAND_APPLICATIONS') and f['path'].endswith('.png')]
open(os.path.join(STUDIO, 'assets/manifest.js'), 'w').write('// generated by application_source/build_manifest.py\nwindow.GF_MANIFEST = ' + json.dumps({'files': files, 'videos': videos, 'gallery': gallery}) + ';\n')
print(len(files), 'files', len(videos), 'videos', len(gallery), 'gallery')
