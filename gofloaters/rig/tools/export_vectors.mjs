// Export the separated artwork: one registered SVG per layer, a layered master SVG (one named group
// per layer, stacking order, Illustrator/Inkscape friendly), a pivot/hierarchy guide SVG and the
// reference PNG the AE builder imports. node export_vectors.mjs <rigDir>
import fs from 'node:fs';
import path from 'node:path';
import {buildSpec} from './rig_spec.mjs';
import {Evaluator} from './preview.mjs';
import {openShooter} from './shoot.mjs';

const rigDir = process.argv[2];
const spec = buildSpec();
const VB = [-250, 40, 1050, 580]; // rig units; every file shares this frame so parts register
const vb = VB.join(' ');
const ringD = (r) => 'M' + r.map((p) => `${p[0]} ${p[1]}`).join('L') + 'Z';
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

function layerBody(l, ev) {
  if (l.lid) {
    // Eyelids are expression-driven; export the half-closed pose (Blink 50) for reference/editing.
    const fill = ev.path(l.lidFill, [], 0, true), edge = ev.path(l.lidEdge, [], 0, false);
    return `<path d="${ringD(fill.map((p) => p.map((v) => +v.toFixed(2))))}" fill="#FFFFFF"/><path d="M${edge.map((p) => `${p[0].toFixed(2)} ${p[1].toFixed(2)}`).join('L')}" fill="none" stroke="#111110" stroke-width="3.2" stroke-linecap="round" stroke-linejoin="round"/>`;
  }
  return l.groups.map((g, i) => `<path id="${l.name}_${g.kind}_${i + 1}" d="${g.rings.map(ringD).join('')}" fill="${g.color}" fill-rule="evenodd"/>`).join('');
}

const outV = path.join(rigDir, 'vectors');
fs.mkdirSync(path.join(outV, 'parts'), {recursive: true});
const ev = new Evaluator(spec, {Blink: [[0, 50]]});
const art = spec.layers.filter((l) => l.type === 'shape');
const head = (title) => `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" viewBox="${vb}" width="${VB[2] * 2}" height="${VB[3] * 2}">\n<title>${esc(title)}</title>\n`;
let manifest = [];
art.forEach((l, i) => {
  const idx = String(art.length - i).padStart(2, '0'); // 01 = back-most, so a sorted file list is the paint order
  const file = `parts/${idx}_${l.name}.svg`;
  const note = l.lid ? 'Eyelid shown half-closed (Blink 50); in After Effects the shape is generated by its path expression.' : '';
  fs.writeFileSync(path.join(outV, file), `${head(`Tilo rig - ${l.name}`)}<desc>Pivot (rig units): ${l.anchor.join(', ')}. Parent: ${l.parent}. ${note}</desc>\n<g id="${l.name}">${layerBody(l, ev)}</g>\n</svg>\n`);
  manifest.push({file, layer: l.name, parent: l.parent, pivot: l.anchor, order_front_to_back: i + 1});
});
// layered master (back -> front in document order = paint order)
const groups = [...art].reverse().map((l) => `<g id="${l.name}" inkscape:groupmode="layer" inkscape:label="${l.name}"${l.lid ? ' style="display:none"' : ''}>${layerBody(l, ev)}</g>`).join('\n');
fs.writeFileSync(path.join(outV, 'Tilo_layered.svg'), `${head('GoFloaters Tilo - layered rig artwork')}<desc>One group per rig layer, in paint order (last = front). Rig units = the supplied SVG's mascot-airplane group space. Eyelid groups are hidden (rest pose = open eyes).</desc>\n${groups}\n</svg>\n`);
// pivots / hierarchy guide
const pv = art.map((l) => `<g><circle cx="${l.anchor[0]}" cy="${l.anchor[1]}" r="3.2" fill="#E2264D" stroke="#fff" stroke-width="1"/><text x="${l.anchor[0] + 4}" y="${l.anchor[1] - 4}" font-family="Arial" font-size="7" fill="#E2264D">${l.name}</text></g>`).join('');
const nulls = spec.layers.filter((l) => l.type === 'null' && l.name !== 'CTRL_Tilo' && l.name !== 'Tilo_Root').map((l) => `<g><rect x="${l.anchor[0] - 3.5}" y="${l.anchor[1] - 3.5}" width="7" height="7" fill="none" stroke="#1F6FEB" stroke-width="1.4"/><text x="${l.anchor[0] + 5}" y="${l.anchor[1] + 9}" font-family="Arial" font-size="7" fill="#1F6FEB">${l.name} (null)</text></g>`).join('');
fs.writeFileSync(path.join(outV, 'Tilo_pivots_guide.svg'), `${head('Tilo rig - pivots')}<g opacity="0.35">${[...art].reverse().filter((l) => !l.lid).map((l) => layerBody(l, ev)).join('')}</g>${pv}${nulls}\n</svg>\n`);
fs.writeFileSync(path.join(outV, 'manifest.json'), JSON.stringify({units: 'rig units (supplied SVG mascot-airplane group space)', viewBox: VB, layers: manifest}, null, 1));

// reference PNG (2 px per rig unit, transparent), registered at rig (-250, 40)
const src = fs.readFileSync(new URL('../../../remotion/public/brand/gofloaters_logo_original.svg', import.meta.url), 'utf8');
const grab = (id) => src.match(new RegExp(`<g id="${id}"[^>]*>([\\s\\S]*?)</g>`))[1];
const W = VB[2] * 2, H = VB[3] * 2;
const refSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="${vb}"><g>${grab('mascot-airplane')}</g><g transform="translate(-300 280)">${grab('speed-lines')}</g></svg>`;
fs.mkdirSync(path.join(rigDir, 'ae/assets'), {recursive: true});
const sh = await openShooter(W, H);
await sh.shoot(refSvg, path.join(rigDir, 'ae/assets/Tilo_reference.png'), {transparent: true});
await sh.close();
console.log(`exported ${art.length} part SVGs, layered SVG, pivots guide, manifest, reference PNG`);
