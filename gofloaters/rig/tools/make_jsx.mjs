// Generate the self-contained After Effects builder (ExtendScript, ES3) from rig_spec.mjs.
// node make_jsx.mjs <out.jsx>
import fs from 'node:fs';
import {buildSpec} from './rig_spec.mjs';
import {ACTING} from './acting.mjs';

const spec = buildSpec();
const hex = (h) => [parseInt(h.slice(1, 3), 16) / 255, parseInt(h.slice(3, 5), 16) / 255, parseInt(h.slice(5, 7), 16) / 255].map((v) => +v.toFixed(5));
const r2 = (v) => Math.round(v * 100) / 100;

const LABEL = {null: 2, plane: 8, dog: 14, face: 10, airflow: 13, ctrl: 1};
const labelOf = (n) =>
  n === 'CTRL_Tilo' ? LABEL.ctrl
    : ['Tilo_Root', 'Flight', 'Dog_Root', 'Dog_Chest'].includes(n) ? LABEL.null
    : n.startsWith('Airflow') ? LABEL.airflow
    : ['Plane_Body', 'Wing', 'Stabilizer', 'Cockpit', 'Propeller', 'Propeller_Blur'].includes(n) ? LABEL.plane
    : ['Goggles', 'Eyelid_Upper', 'Eyelid_Lower', 'Pupil', 'Eye_White', 'Face', 'Ear_Near', 'Ear_Far', 'Head'].includes(n) ? LABEL.face
    : LABEL.dog;

// Compact, ES3-safe data: layers back -> front (AE adds each new layer on top).
const layers = [...spec.layers].reverse().map((l) => {
  const o = {
    name: l.name, type: l.type, parent: l.parent, anchor: l.anchor, position: l.position,
    scale: l.scale || [100, 100], label: labelOf(l.name), comment: l.comment || '',
    expr: l.expr || {}, motionBlur: !!l.motionBlur, mask: l.mask || null,
  };
  if (l.groups) {
    o.groups = l.groups.map((g) => ({kind: g.kind, color: hex(g.color), rings: g.rings.map((r) => r.map((p) => [r2(p[0]), r2(p[1])]))}));
  }
  if (l.pathExpr) o.pathExpr = l.pathExpr;
  if (l.groupExpr) o.groupExpr = l.groupExpr;
  if (l.lid) {
    o.lid = l.lid;
    o.lidFill = l.lidFill;
    o.lidEdge = l.lidEdge;
  }
  if (l.effects) o.effects = l.effects;
  return o;
});

const data = {
  comp: spec.comp,
  controls: spec.controls.map((c) => ({name: c.name, type: c.type, def: c.def})),
  layers,
  eye: spec.eyeOutline.map((p) => [r2(p[0]), r2(p[1])]),
  acting: ACTING,
  // reference PNG (assets/Tilo_reference.png) is rendered at 2 px per rig unit from rig (-250, 40)
  refOrigin: [-250, 40],
  refScale: 50,
};

const jsx = `// GoFloaters - Tilo mascot rig builder for Adobe After Effects (generated by make_jsx.mjs; do not edit by hand)
// Run: File > Scripts > Run Script File... and pick this file (keep the "assets" folder next to it).
// Builds: "Tilo_Rig" (clean rig) and "Tilo_Acting_Test" (every control keyframed, with captions),
// organised in project folders, all artwork as native, editable shape layers.
// Requires After Effects 2019 (16.0) or later with the JavaScript expression engine.
(function () {
  var DATA = ${JSON.stringify(data)};

  function hasEff(o, k) { return Object.prototype.hasOwnProperty.call(o, k); }

  function makeShape(ring, closed) {
    var s = new Shape();
    s.vertices = ring;
    var z = [], i;
    for (i = 0; i < ring.length; i++) z.push([0, 0]);
    s.inTangents = z;
    s.outTangents = z;
    s.closed = closed;
    return s;
  }

  function addFill(vecs, color, evenOdd) {
    var f = vecs.addProperty("ADBE Vector Graphic - Fill");
    f.property("ADBE Vector Fill Color").setValue([color[0], color[1], color[2], 1]);
    f.property("ADBE Vector Fill Rule").setValue(evenOdd ? 2 : 1);
    return f;
  }

  function buildShapeLayer(comp, L) {
    var layer = comp.layers.addShape();
    layer.name = L.name;
    var contents = layer.property("ADBE Root Vectors Group");
    var gi, ri;
    if (L.lid) {
      // Eyelid: inked edge (stroke) over a white lid, both driven by path expressions.
      var ge = contents.addProperty("ADBE Vector Group");
      ge.name = "Lid Edge";
      var ve = ge.property("ADBE Vectors Group");
      var pe = ve.addProperty("ADBE Vector Shape - Group");
      pe.property("ADBE Vector Shape").setValue(makeShape([[0, 0], [10, 0]], false));
      pe.property("ADBE Vector Shape").expression = L.lidEdge;
      var st = ve.addProperty("ADBE Vector Graphic - Stroke");
      st.property("ADBE Vector Stroke Color").setValue([0.06667, 0.06667, 0.06275, 1]);
      st.property("ADBE Vector Stroke Width").setValue(3.2);
      st.property("ADBE Vector Stroke Line Cap").setValue(2);
      st.property("ADBE Vector Stroke Line Join").setValue(2);
      var gf = contents.addProperty("ADBE Vector Group");
      gf.name = "Lid";
      var vf = gf.property("ADBE Vectors Group");
      var pf = vf.addProperty("ADBE Vector Shape - Group");
      pf.property("ADBE Vector Shape").setValue(makeShape([[0, 0], [10, 0], [10, 10]], true));
      pf.property("ADBE Vector Shape").expression = L.lidFill;
      addFill(vf, [1, 1, 1], false);
      return layer;
    }
    // Groups are listed bottom -> top in the data; the first group in Contents draws on top.
    for (gi = L.groups.length - 1; gi >= 0; gi--) {
      var G = L.groups[gi];
      var grp = contents.addProperty("ADBE Vector Group");
      grp.name = (G.kind === "ink" ? "Ink" : "Fill") + " " + (gi + 1);
      var vecs = grp.property("ADBE Vectors Group");
      for (ri = 0; ri < G.rings.length; ri++) {
        var pg = vecs.addProperty("ADBE Vector Shape - Group");
        pg.name = "Path " + (ri + 1);
        pg.property("ADBE Vector Shape").setValue(makeShape(G.rings[ri], true));
        if (L.pathExpr) pg.property("ADBE Vector Shape").expression = L.pathExpr;
      }
      addFill(vecs, G.color, true);
      if (L.groupExpr && L.groupExpr.position) {
        grp.property("ADBE Vector Transform Group").property("ADBE Vector Position").expression = L.groupExpr.position;
      }
    }
    return layer;
  }

  function addEffects(layer, L) {
    if (!L.effects) return;
    var i;
    for (i = 0; i < L.effects.length; i++) {
      var E = L.effects[i];
      if (E.type === "directionalBlur") {
        var fx = layer.property("ADBE Effect Parade").addProperty("ADBE Motion Blur");
        fx.name = "Blade Blur";
        fx.property("ADBE Motion Blur-0001").setValue(E.direction);
        fx.property("ADBE Motion Blur-0002").expression = E.lengthExpr;
      }
    }
  }

  function addControls(ctrl) {
    var i, fx, mn = {slider: "ADBE Slider Control", angle: "ADBE Angle Control", checkbox: "ADBE Checkbox Control"};
    for (i = 0; i < DATA.controls.length; i++) {
      var c = DATA.controls[i];
      fx = ctrl.property("ADBE Effect Parade").addProperty(mn[c.type]);
      fx.name = c.name;
      fx.property(1).setValue(c.def);
    }
  }

  function buildRig(comp) {
    var byName = {}, i, L, layer;
    for (i = 0; i < DATA.layers.length; i++) {
      L = DATA.layers[i];
      if (L.type === "null") {
        layer = comp.layers.addNull();
        layer.name = L.name;
      } else {
        layer = buildShapeLayer(comp, L);
      }
      layer.label = L.label;
      if (L.comment) layer.comment = L.comment;
      byName[L.name] = layer;
    }
    addControls(byName.CTRL_Tilo);
    // Parent first, then write every transform value (any parenting compensation is overwritten).
    for (i = 0; i < DATA.layers.length; i++) {
      L = DATA.layers[i];
      if (L.parent) byName[L.name].parent = byName[L.parent];
    }
    for (i = 0; i < DATA.layers.length; i++) {
      L = DATA.layers[i];
      layer = byName[L.name];
      var tr = layer.property("ADBE Transform Group");
      tr.property("ADBE Anchor Point").setValue(L.anchor);
      tr.property("ADBE Position").setValue(L.position);
      tr.property("ADBE Scale").setValue(L.scale);
      tr.property("ADBE Rotate Z").setValue(0);
      if (hasEff(L.expr, "rotation")) tr.property("ADBE Rotate Z").expression = L.expr.rotation;
      if (hasEff(L.expr, "position")) tr.property("ADBE Position").expression = L.expr.position;
      if (hasEff(L.expr, "scale")) tr.property("ADBE Scale").expression = L.expr.scale;
      if (hasEff(L.expr, "opacity")) tr.property("ADBE Opacity").expression = L.expr.opacity;
      if (L.mask === "eye") {
        var m = layer.property("ADBE Mask Parade").addProperty("ADBE Mask Atom");
        m.name = "Inside Goggles";
        m.property("ADBE Mask Shape").setValue(makeShape(DATA.eye, true));
      }
      addEffects(layer, L);
      if (L.motionBlur) layer.motionBlur = true;
    }
    comp.motionBlur = true;
    return byName;
  }

  function easeKeys(prop, keys, isCheckbox) {
    var i, k;
    for (i = 0; i < keys.length; i++) prop.setValueAtTime(keys[i][0], keys[i][1]);
    for (i = 1; i <= prop.numKeys; i++) {
      k = keys[i - 1];
      if (isCheckbox || k[2] === "hold") {
        prop.setInterpolationTypeAtKey(i, KeyframeInterpolationType.HOLD, KeyframeInterpolationType.HOLD);
      } else if (k[2] === "linear") {
        prop.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);
      } else {
        prop.setInterpolationTypeAtKey(i, KeyframeInterpolationType.BEZIER, KeyframeInterpolationType.BEZIER);
        prop.setTemporalEaseAtKey(i, [new KeyframeEase(0, 33.333)], [new KeyframeEase(0, 33.333)]);
      }
    }
  }

  function addCaptions(comp, A) {
    var t = comp.layers.addText("Tilo rig");
    t.name = "CAPTION";
    t.label = 1;
    var tp = t.property("ADBE Text Properties").property("ADBE Text Document");
    var i;
    for (i = 0; i < A.captions.length; i++) {
      var doc = tp.value;
      doc.text = A.captions[i][1] + "\\r" + A.captions[i][2];
      doc.fontSize = 34;
      doc.applyFill = true;
      doc.fillColor = [0.06667, 0.06667, 0.06275];
      doc.justification = ParagraphJustification.LEFT_JUSTIFY;
      tp.setValueAtTime(A.captions[i][0], doc);
    }
    for (i = 1; i <= tp.numKeys; i++) tp.setInterpolationTypeAtKey(i, KeyframeInterpolationType.HOLD, KeyframeInterpolationType.HOLD);
    t.property("ADBE Transform Group").property("ADBE Position").setValue([70, comp.height - 92]);
    return t;
  }

  app.beginUndoGroup("Build Tilo rig");
  try {
    try { app.project.expressionEngine = "javascript-1.0"; } catch (e0) {}
    var proj = app.project;
    var root = proj.items.addFolder("GoFloaters Tilo Rig");
    var fComps = proj.items.addFolder("01 Comps");
    var fRef = proj.items.addFolder("02 Reference");
    fComps.parentFolder = root;
    fRef.parentFolder = root;
    var C = DATA.comp;

    var rig = proj.items.addComp("Tilo_Rig", C.width, C.height, 1, C.duration, C.fps);
    rig.parentFolder = fComps;
    rig.bgColor = [0.914, 0.937, 0.949];
    var R1 = buildRig(rig);

    var A = DATA.acting;
    var act = proj.items.addComp("Tilo_Acting_Test", C.width, C.height, 1, A.duration, C.fps);
    act.parentFolder = fComps;
    act.bgColor = [0.914, 0.937, 0.949];
    var L2 = buildRig(act);
    var root2 = L2.Tilo_Root.property("ADBE Transform Group");
    root2.property("ADBE Position").setValue(A.rootPosition);
    root2.property("ADBE Scale").setValue(A.rootScale);
    var ctrl = L2.CTRL_Tilo.property("ADBE Effect Parade");
    var n, i;
    for (n in A.keys) {
      if (!hasEff(A.keys, n)) continue;
      var isCb = false;
      for (i = 0; i < DATA.controls.length; i++) if (DATA.controls[i].name === n) isCb = DATA.controls[i].type === "checkbox";
      easeKeys(ctrl.property(n).property(1), A.keys[n], isCb);
    }
    addCaptions(act, A);

    // Reference: the supplied logo artwork, placed to register with the rig (guide layer, off).
    var refFile = new File(new File($.fileName).parent.fsName + "/assets/Tilo_reference.png");
    if (refFile.exists) {
      var item = proj.importFile(new ImportOptions(refFile));
      item.parentFolder = fRef;
      var ref = rig.layers.add(item);
      ref.name = "REFERENCE (original logo)";
      ref.guideLayer = true;
      ref.enabled = false;
      ref.moveToEnd();
      ref.parent = R1.Tilo_Root;
      var rt = ref.property("ADBE Transform Group");
      rt.property("ADBE Anchor Point").setValue([0, 0]);
      rt.property("ADBE Position").setValue(DATA.refOrigin);
      rt.property("ADBE Scale").setValue([DATA.refScale, DATA.refScale]);
      rt.property("ADBE Rotate Z").setValue(0);
    }
    rig.openInViewer();
  } catch (err) {
    alert("Tilo rig builder stopped: " + err.toString() + (err.line ? " (line " + err.line + ")" : ""));
  } finally {
    app.endUndoGroup();
  }
})();
`;
fs.writeFileSync(process.argv[2], jsx);
console.log(`wrote ${process.argv[2]} (${(jsx.length / 1024).toFixed(0)} KB)`);
